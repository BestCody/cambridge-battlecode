"""Export trained XGBoost heads to self-contained C++ headers for a bot.

    python training/export_cpp.py                         # every best/ model under checkpoints/
    python training/export_cpp.py --hero vesper --verify-cpp
    python training/export_cpp.py --out ../../bots/pdi-clone/src/pdi/generated

Writes (default training/cpp/generated/; with --out elsewhere the runtime headers pdi_tree.h,
pdi_features.h and pdi_policy.h are copied to the folder above it, so it is self-contained):
  pdi_feature_index.h   feature indices (F_round, ...) + PDI_FEATURE_VERSION, from feature_spec.json
  <hero>_<head>.h       one model: flat node array, tree roots, base margin, class ids
  pdi_models.h          includes them all + pdi::models::find(hero_type, head) lookup

Each model is checked before writing: a pure-Python walk of the exported arrays must reproduce
xgboost's own output margins on held-out rows. With --verify-cpp the headers are also compiled with
g++ and run against the same rows.
"""
import argparse
import json
import math
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import features as F  # noqa: E402
from train import HEROES  # noqa: E402

TRAINING = Path(__file__).resolve().parent
DEFAULT_CKPT = TRAINING.parent / "checkpoints"
DEFAULT_OUT = TRAINING / "cpp" / "generated"


def parse_base_score(raw, n_groups):
    raw = str(raw).strip("[]")
    vals = [float(v) for v in raw.split(",") if v.strip()]
    if len(vals) == 1:
        vals = vals * n_groups
    return vals


def load_model(path):
    """Flatten an xgboost JSON model into node arrays. Returns dict with nodes, roots, groups, base."""
    m = json.loads(Path(path).read_text())
    learner = m["learner"]
    obj = learner["objective"]["name"]
    booster = learner["gradient_booster"]
    if booster["name"] != "gbtree":
        raise ValueError(f"unsupported booster {booster['name']}")
    model = booster["model"]
    n_groups = int(learner["learner_model_param"].get("num_class", "0")) or 1
    base = parse_base_score(learner["learner_model_param"]["base_score"], n_groups)
    if obj == "binary:logistic":
        base = [math.log(b / (1 - b)) for b in base]       # probability -> logit margin
    elif not obj.startswith("multi:"):
        raise ValueError(f"unsupported objective {obj}")
    nodes, roots, groups = [], [], []
    for t, tree in enumerate(model["trees"]):
        off = len(nodes)
        roots.append(off)
        groups.append(int(model["tree_info"][t]))
        L, R = tree["left_children"], tree["right_children"]
        idx, cond, dl = tree["split_indices"], tree["split_conditions"], tree["default_left"]
        if tree.get("split_type") and any(tree["split_type"]):
            raise ValueError("categorical splits are not supported")
        for i in range(len(L)):
            if L[i] == -1:
                nodes.append((-1, 0, float(cond[i]), 0, 0))           # leaf: value in cond
            else:
                nodes.append((int(idx[i]), int(dl[i]), float(cond[i]), off + L[i], off + R[i]))
    return {"objective": obj, "nodes": nodes, "roots": roots, "groups": groups, "base": base, "n_groups": n_groups}


def margins_py(mdl, X):
    """Walk the flattened arrays exactly as the C++ does (float32 comparisons)."""
    nodes = mdl["nodes"]
    feat = np.array([n[0] for n in nodes]); dl = np.array([n[1] for n in nodes], bool)
    val = np.array([n[2] for n in nodes], np.float32); left = np.array([n[3] for n in nodes]); right = np.array([n[4] for n in nodes])
    out = np.tile(np.array(mdl["base"], np.float64), (len(X), 1))
    X = X.astype(np.float32)
    rows = np.arange(len(X))
    for root, g in zip(mdl["roots"], mdl["groups"]):
        cur = np.full(len(X), root)
        for _ in range(64):
            f = feat[cur]
            internal = f >= 0
            if not internal.any():
                break
            x = X[rows, np.where(internal, f, 0)]
            go_left = np.where(np.isnan(x), dl[cur], x < val[cur])
            cur = np.where(internal, np.where(go_left, left[cur], right[cur]), cur)
        out[:, g] += val[cur]
    return out


def cpp_float(v):
    if math.isinf(v):
        return "INFINITY" if v > 0 else "-INFINITY"
    s = f"{float(np.float32(v)):.9g}"   # 9 significant digits round-trip a float32 exactly
    return (s if any(c in s for c in ".e") else s + ".0") + "f"


def write_header(mdl, state, ident, path):
    nodes = mdl["nodes"]
    classes = state["classes"]
    lines = [f"// Generated by training/export_cpp.py from {state['hero']}/{state['head']} (best round "
             f"{state['history']['best_round']}, feature version {state['feature_version']}). Do not edit.",
             "#pragma once", '#include "../pdi_tree.h"', "", "namespace pdi::models {", "",
             f"inline constexpr Node {ident}_nodes[] = {{"]
    for f, d, v, l, r in nodes:
        lines.append(f"    {{{f}, {d}, {cpp_float(v)}, {l}, {r}}},")
    lines.append("};")
    lines.append(f"inline constexpr std::int32_t {ident}_roots[] = {{{', '.join(map(str, mdl['roots']))}}};")
    lines.append(f"inline constexpr std::uint8_t {ident}_groups[] = {{{', '.join(map(str, mdl['groups']))}}};")
    lines.append(f"inline constexpr float {ident}_base[] = {{{', '.join(cpp_float(b) for b in mdl['base'])}}};")
    lines.append(f"inline constexpr std::int16_t {ident}_classes[] = {{{', '.join(map(str, classes))}}};")
    names = ", ".join(json.dumps(n) for n in state["class_names"])
    lines.append(f"inline constexpr const char* {ident}_class_names[] = {{{names}}};")
    lines.append(f"inline constexpr Model {ident} = {{{ident}_nodes, {ident}_roots, {ident}_groups, "
                 f"{len(mdl['roots'])}, {ident}_base, {mdl['n_groups']}, {ident}_classes, {len(classes)}, "
                 f"{ident}_class_names, {int(mdl['objective'] == 'binary:logistic')}}};")
    lines += ["", "} // namespace pdi::models", ""]
    path.write_text("\n".join(lines), encoding="utf-8")


def write_feature_index(out):
    spec = json.loads((TRAINING / "data" / "feature_spec.json").read_text())
    lines = ["// Generated by training/export_cpp.py from data/feature_spec.json. Do not edit.", "#pragma once", "",
             "namespace pdi {", "", f"inline constexpr int PDI_FEATURE_VERSION = {spec['version']};",
             f"inline constexpr int NUM_FEATURES = {len(spec['features'])};", "", "enum Feature : int {"]
    lines += [f"    F_{n} = {i}," for i, n in enumerate(spec["features"])]
    lines += ["};", "", "inline constexpr const char* FEATURE_NAMES[] = {"]
    lines += [f'    "{n}",' for n in spec["features"]]
    lines += ["};", "", "} // namespace pdi", ""]
    (out / "pdi_feature_index.h").write_text("\n".join(lines), encoding="utf-8")


def sample_rows(hero_type, head, n=400):
    """Held-out rows for this hero/head (any game), for verification."""
    rng = np.random.default_rng(1)
    for f in sorted((TRAINING / "data" / "features").glob("*.npz"))[::-1]:
        with np.load(f) as z:
            if head == "shop":
                X, y, h = z["X_shop"], z["y_shop"], z["hero_shop"]
            else:
                X, y, h = z["X"], z[f"y_{head}"], z["hero"]
            idx = np.nonzero((h == hero_type) & (y >= 0))[0]
            if len(idx) >= 20:
                return X[rng.choice(idx, min(n, len(idx)), replace=False)]
    return None


CPP_TEST = r'''
#include <cstdio>
#include <cstdlib>
#include <cmath>
#include <vector>
#include "pdi_models.h"
int main(int argc, char** argv) {
    const pdi::Model* m = pdi::models::find(std::atoi(argv[1]), argv[2]);
    if (!m) { std::printf("missing\n"); return 2; }
    FILE* f = std::fopen(argv[3], "rb");
    int n, nf; std::fread(&n, 4, 1, f); std::fread(&nf, 4, 1, f);
    std::vector<float> x(nf), out(m->n_groups);
    for (int i = 0; i < n; ++i) {
        std::fread(x.data(), 4, nf, f);
        pdi::margins(*m, x.data(), out.data());
        for (int g = 0; g < m->n_groups; ++g) std::printf("%.6f ", out[g]);
        std::printf("\n");
    }
}
'''


# Boosted trees are sequential, so the first N rounds form a complete, smaller model. These caps keep a
# typical acting turn (move + attack + ability + ward + recall) around 3.5k tree levels, i.e. roughly
# 40k fuel at ~12 wasm instructions per level, leaving room for the features. Check the accuracy cost
# of any cap with budget_curve.py.
FUEL_PER_LEVEL = 12
BUDGET = {"move": 30, "attack": 20, "ability": 20, "ability_target": 20, "dash": 20, "shop": 20, "recall": 10,
          "cancel": 10, "ward": 10, "ward_offset": 10, "submit": 20, "lock": 10, "teleport": 20, "tp_offset": 10,
          "recall_commit": 0}   # 0 = not exported (analysis-only head)
TYPICAL_TURN = ("move", "attack", "ability", "ward", "recall")


def tree_levels(mdl):
    """Levels walked per call if every tree goes to its deepest leaf (an upper bound)."""
    nodes, total = mdl["nodes"], 0
    for root in mdl["roots"]:
        stack, deepest = [(root, 0)], 0
        while stack:
            i, d = stack.pop()
            if nodes[i][0] < 0:
                deepest = max(deepest, d)
            else:
                stack += [(nodes[i][3], d + 1), (nodes[i][4], d + 1)]
        total += deepest
    return total


def main():
    import xgboost as xgb

    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--ckpt-dir", default=str(DEFAULT_CKPT))
    p.add_argument("--out", default=str(DEFAULT_OUT))
    p.add_argument("--hero", default="all")
    p.add_argument("--which", default="best", choices=["best", "current"])
    p.add_argument("--rounds", default="",
                   help="per-head round caps overriding the fuel budget, e.g. 'move=60,attack=40'; 'all' keeps every round")
    p.add_argument("--verify-cpp", action="store_true", help="compile with g++ and compare against xgboost")
    args = p.parse_args()

    budget = dict(BUDGET)
    if args.rounds == "all":
        budget = {k: (v if v == 0 else 10 ** 9) for k, v in budget.items()}
    elif args.rounds:
        for kv in args.rounds.split(","):
            k, v = kv.split("=")
            budget[k.strip()] = int(v)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    # The runtime headers live one level above generated/ (generated headers include "../pdi_tree.h").
    if out.parent.resolve() != (TRAINING / "cpp").resolve():
        for h in ("pdi_tree.h", "pdi_features.h", "pdi_policy.h"):
            shutil.copy(TRAINING / "cpp" / h, out.parent / h)
    write_feature_index(out)
    heroes = list(HEROES) if args.hero == "all" else args.hero.split(",")
    exported = []
    for hero in heroes:
        for state_path in sorted((Path(args.ckpt_dir) / hero).glob(f"*/{args.which}/state.json")):
            state = json.loads(state_path.read_text())
            head = state["head"]
            if state["feature_version"] != F.FEATURE_VERSION:
                print(f"skip {hero}/{head}: trained on feature version {state['feature_version']}, now {F.FEATURE_VERSION}")
                continue
            cap = budget.get(head, 10 ** 9)
            if cap == 0:
                continue
            model_path = state_path.parent / "model.json"
            booster = xgb.Booster(model_file=str(model_path))
            if booster.num_boosted_rounds() > cap:
                booster = booster[:cap]
                tmp = Path(tempfile.mkdtemp()) / "m.json"
                booster.save_model(str(tmp))
                model_path = tmp
            mdl = load_model(model_path)
            X = sample_rows(HEROES[hero], head)
            if X is not None:
                ref = booster.predict(xgb.DMatrix(X, feature_names=F.NAMES, missing=np.nan), output_margin=True)
                ref = ref.reshape(len(X), -1)
                mine = margins_py(mdl, X)
                err = float(np.abs(ref - mine).max())
                agree = float((ref.argmax(1) == mine.argmax(1)).mean()) if ref.shape[1] > 1 else float(((ref > 0) == (mine > 0)).mean())
                if err > 1e-3 or agree < 0.999:
                    sys.exit(f"{hero}/{head}: exported trees disagree with xgboost (max margin err {err:.2e}, argmax agree {agree:.3f})")
            ident = f"{hero}_{head}"
            write_header(mdl, state, ident, out / f"{ident}.h")
            levels = tree_levels(mdl)
            exported.append((hero, head, ident, mdl, levels, X))
            print(f"exported {ident:<24} {booster.num_boosted_rounds():4d} rounds {len(mdl['roots']):5d} trees "
                  f"{len(mdl['nodes']):7d} nodes  <= {levels:6d} levels (~{levels * FUEL_PER_LEVEL // 1000}k fuel) per call")

    lines = ["// Generated by training/export_cpp.py. Do not edit.", "#pragma once", "#include <cstring>",
             '#include "../pdi_tree.h"', '#include "pdi_feature_index.h"']
    lines += [f'#include "{e[2]}.h"' for e in exported]
    lines += ["", "namespace pdi::models {", "",
              "// Model for a champion type (cambc::champion_type as int) and head name; nullptr if not exported.",
              "inline const Model* find(int champion_type, const char* head) {"]
    for hero, head, ident, *_ in exported:
        lines.append(f'    if (champion_type == {HEROES[hero]} && std::strcmp(head, "{head}") == 0) return &{ident};')
    lines += ["    return nullptr;", "}", "", "} // namespace pdi::models", ""]
    (out / "pdi_models.h").write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {len(exported)} models to {out}")
    for hero in heroes:
        lv = sum(e[4] for e in exported if e[0] == hero and e[1] in TYPICAL_TURN)
        if lv:
            print(f"  {hero:<9} typical acting turn ({'+'.join(TYPICAL_TURN)}): <= {lv} levels "
                  f"~ {lv * FUEL_PER_LEVEL // 1000}k fuel of 100k, before features")

    if args.verify_cpp and exported:
        gxx = shutil.which("g++") or shutil.which("clang++")
        if not gxx:
            sys.exit("--verify-cpp needs g++ or clang++ on PATH")
        work = Path(tempfile.mkdtemp())
        (work / "test.cpp").write_text(CPP_TEST)
        include = [f"-I{out}"]
        exe = work / "test.exe"
        res = subprocess.run([gxx, "-std=c++20", "-O1", *include, str(work / "test.cpp"), "-o", str(exe)],
                             capture_output=True, text=True)
        if res.returncode:
            sys.exit("g++ failed:\n" + res.stderr[-3000:])
        for hero, head, ident, mdl, _, X in exported:
            if X is None:
                continue
            data = work / f"{ident}.bin"
            with open(data, "wb") as f:
                f.write(np.array([len(X), X.shape[1]], np.int32).tobytes())
                f.write(X.astype(np.float32).tobytes())
            res = subprocess.run([str(exe), str(HEROES[hero]), head, str(data)], capture_output=True, text=True, check=True)
            got = np.array([[float(v) for v in l.split()] for l in res.stdout.strip().splitlines()])
            ref = margins_py(mdl, X)
            err = float(np.abs(got - ref).max())
            print(f"  c++ {ident:<24} max |margin - python| = {err:.2e}  {'OK' if err < 1e-3 else 'MISMATCH'}")


if __name__ == "__main__":
    main()
